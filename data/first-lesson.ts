export const firstLesson = `L’intelligence artificielle (IA) désigne un ensemble de méthodes informatiques qui permettent à des systèmes de réaliser des tâches telles que reconnaître des images, analyser du langage, trouver des régularités dans des données ou produire du contenu.

## 1. Les grandes familles

IA à règles : un système applique des règles explicitement définies. Apprentissage automatique : il apprend des régularités à partir d’exemples. Apprentissage profond : il utilise des réseaux de neurones à plusieurs couches. IA générative : certains modèles peuvent produire du texte, des images, du son ou d’autres contenus.

## 2. Comment reconnaître ces familles ?

Une IA fondée sur des règles suit des instructions décidées par un humain : si une condition est remplie, elle applique une action. Dans l’apprentissage automatique, les règles utiles sont plutôt déduites de données. L’apprentissage profond constitue une sous-famille de l’apprentissage automatique utilisant des réseaux neuronaux à plusieurs couches. Enfin, l’IA générative décrit des systèmes capables de créer de nouveaux contenus : ce n’est pas une catégorie strictement parallèle aux précédentes, car elle peut employer l’apprentissage profond.

## 3. Des usages concrets

Les recommandations de films, la transcription vocale, les filtres anti-spam et les assistants conversationnels illustrent plusieurs applications possibles de l’IA.

Exercice : demandez à un assistant IA d’expliquer en trois phrases ce qu’est l’apprentissage automatique, puis comparez l’explication à une source pédagogique fiable.

## 4. Les limites essentielles

Une IA peut générer des informations fausses, manquer de contexte ou reproduire des biais. Il faut garder un esprit critique, en particulier pour les décisions sensibles, et éviter de partager inutilement des données privées.

Ce cours est un exemple rédigé pour le prototype. Les contenus des autres leçons seront produits et vérifiés séparément.`;
